import { access, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const references = new Set();

function addReference(rawReference, baseDirectory = '') {
    if (!rawReference) return;

    const cleanReference = rawReference
        .trim()
        .replace(/^['"]|['"]$/g, '')
        .split(/[?#]/, 1)[0];

    if (!cleanReference || cleanReference.includes('${')) return;
    if (/^(?:https?:|data:|blob:|mailto:|tel:|#)/i.test(cleanReference)) return;

    const normalized = cleanReference.startsWith('/')
        ? cleanReference.slice(1)
        : path.posix.normalize(path.posix.join(baseDirectory, cleanReference.replace(/^\.\//, '')));

    if (normalized.startsWith('assets/')) references.add(normalized);
}

async function collectHtmlReferences(fileName) {
    const html = await readFile(path.join(projectRoot, fileName), 'utf8');

    for (const match of html.matchAll(/\b(?:src|href)=["']([^"']+)["']/gi)) {
        addReference(match[1]);
    }

    for (const match of html.matchAll(/\bsrcset=["']([^"']+)["']/gi)) {
        for (const candidate of match[1].split(',')) {
            addReference(candidate.trim().split(/\s+/, 1)[0]);
        }
    }

    for (const match of html.matchAll(/["']((?:\.\/)?assets\/[^"'\s,]+)["']/g)) {
        addReference(match[1]);
    }

    if (fileName === 'index.html') {
        for (const match of html.matchAll(/['"](\d{2})['"]\s*:\s*\{[\s\S]*?imagesCount:\s*(\d+)/g)) {
            const [, projectId, imageCountText] = match;
            const imageCount = Number(imageCountText);
            for (let imageIndex = 1; imageIndex <= imageCount; imageIndex += 1) {
                const suffix = String(imageIndex).padStart(2, '0');
                references.add(`assets/works/${projectId}/${projectId}_image_${suffix}.webp`);
            }
        }
    }
}

async function collectCssReferences(fileName, baseDirectory) {
    const css = await readFile(path.join(projectRoot, fileName), 'utf8');
    for (const match of css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/gi)) {
        addReference(match[1], baseDirectory);
    }
}

await Promise.all([
    collectHtmlReferences('index.html'),
    collectHtmlReferences('index-dark.html'),
    collectCssReferences('assets/vendor/inter.css', 'assets/vendor'),
]);

// These collections are generated by number in JavaScript rather than written
// as individual literal paths in the HTML.
for (let logoIndex = 1; logoIndex <= 30; logoIndex += 1) {
    references.add(`assets/project_logo/logo_${String(logoIndex).padStart(2, '0')}.svg`);
}
for (let sceneIndex = 1; sceneIndex <= 7; sceneIndex += 1) {
    references.add(`assets/scene/scene_${String(sceneIndex).padStart(2, '0')}.webp`);
}

const missing = [];
for (const assetPath of [...references].sort()) {
    try {
        await access(path.join(projectRoot, assetPath));
    } catch {
        missing.push(assetPath);
    }
}

if (missing.length) {
    console.error(`Missing ${missing.length} referenced asset${missing.length === 1 ? '' : 's'}:`);
    missing.forEach((assetPath) => console.error(`- ${assetPath}`));
    process.exitCode = 1;
} else {
    console.log(`Asset check passed: ${references.size} referenced files found.`);
}
